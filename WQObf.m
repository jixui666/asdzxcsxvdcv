static const uint8_t kPathC[] = {
    0x44, 0x17, 0x16, 0x6e, 0x38, 0x62, 0x68, 0x5a, 0x1c, 0x59, 0x54, 0x57, 0xab, 0xb3, 0xa4, 0xef,
